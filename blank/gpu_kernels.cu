// ============================================================================
// Kernel 1: Gumbel-Max Categorical Sampling
// ============================================================================
//
// This kernel replaces the CuPy expression:
//
//   u = cp.clip(cp.random.random((W, N)), eps, 1-eps)
//   gumbel = -cp.log(-cp.log(u))
//   next = cp.argmax(cp.log(P_walker) + gumbel, axis=1)
//
// In a real deployment, the Gumbel noise would be generated by cuRAND
// (via curandGenerateUniform) and piped directly into kernel memory.
// The kernel below demonstrates the argmax-with-noise pattern at the
// thread-block level.

__global__ void gumbel_max_kernel(
    const float* __restrict__ log_P,    // (total_walkers, N) row-major
    const float* __restrict__ gumbel,    // (total_walkers, N) pre-generated
    int* __restrict__ next_nodes,        // (total_walkers,) output
    int total_walkers,
    int N
) {
    // Each block handles one walker (BLOCK_DIM is a warp = 32 threads).
    // Threads within the warp cooperatively find the argmax via
    // warp-level reduction, avoiding per-thread branching.

    int walker_idx = blockIdx.x;  // one walker per block
    if (walker_idx >= total_walkers) return;

    int tid = threadIdx.x;        // 0..31 within the warp

    // --- Cooperative argmax over the N nodes (striped access) ---
    // Each thread scans N/BLOCK_DIM elements.
    float best_val = -1e38f;
    int   best_idx = -1;

    const float* row_log_P = log_P + walker_idx * N;
    const float* row_gumbel = gumbel + walker_idx * N;

    for (int j = tid; j < N; j += blockDim.x) {
        float score = row_log_P[j] + row_gumbel[j];
        if (score > best_val) {
            best_val = score;
            best_idx = j;
        }
    }

    // --- Warp-level reduction to find the global argmax ---
    // __shfl_xor_sync broadcasts the best value across all threads
    // in the warp, avoiding shared memory entirely.
    for (int offset = warpSize / 2; offset > 0; offset >>= 1) {
        int peer_idx = __shfl_xor_sync(0xffffffff, best_idx, offset);
        float peer_val = __shfl_xor_sync(0xffffffff, best_val, offset);
        if (peer_val > best_val || (peer_val == best_val && peer_idx < best_idx)) {
            best_val = peer_val;
            best_idx = peer_idx;
        }
    }

    // Thread 0 writes the result.
    if (tid == 0) {
        next_nodes[walker_idx] = best_idx;
    }
}


// ============================================================================
// Kernel 2: Tiled GEMM (for reference — cuBLAS is preferred in production)
// ============================================================================
//
// Our pipeline calls X_k @ X_k.T which CuPy dispatches to cuBLAS.
// cuBLAS on SM 8.9 (Ada) can use Tensor Core fp16 * fp16 + fp32 accumulate.
// The tiled kernel below shows the textbook shared-memory blocking pattern
// that cuBLAS's internal heuristics would use for a small matrix.
//
// In practice, cuBLAS's cublasGemmEx with CUBLAS_GEMM_DEFAULT_TENSOR_OP
// is faster than any hand-written GEMM for N ≥ 112, so we keep the CuPy
// path.  This kernel exists ONLY for pedagogical completeness.

#define TILE_SIZE 16

__global__ void sgemm_nn_tiled(
    const float* __restrict__ A,   // (M, K) row-major
    const float* __restrict__ B,   // (K, N) row-major
    float* __restrict__ C,         // (M, N) row-major  (output)
    int M, int N, int K
) {
    // Block indices identify which tile of C this block computes.
    int bx = blockIdx.x;  // column tile index (0..N/TILE_SIZE)
    int by = blockIdx.y;  // row tile index    (0..M/TILE_SIZE)

    int tx = threadIdx.x;  // column within tile
    int ty = threadIdx.y;  // row within tile

    // Global row/col of the first element in this block's tile of C.
    int row = by * TILE_SIZE + ty;
    int col = bx * TILE_SIZE + tx;

    // Accumulator for this thread's C[row, col] element.
    float acc = 0.0f;

    // Slide the K-dimension in TILE_SIZE-sized chunks.
    for (int kk = 0; kk < K; kk += TILE_SIZE) {
        // Cooperative load of A and B tiles into shared memory.
        __shared__ float As[TILE_SIZE][TILE_SIZE];
        __shared__ float Bs[TILE_SIZE][TILE_SIZE];

        if (row < M && (kk + tx) < K)
            As[ty][tx] = A[row * K + (kk + tx)];
        else
            As[ty][tx] = 0.0f;

        if ((kk + ty) < K && col < N)
            Bs[ty][tx] = B[(kk + ty) * N + col];
        else
            Bs[ty][tx] = 0.0f;

        __syncthreads();

        // Inner product over this tile.
        for (int ki = 0; ki < TILE_SIZE; ki++) {
            acc += As[ty][ki] * Bs[ki][tx];
        }

        __syncthreads();
    }

    // Write result (with bounds check).
    if (row < M && col < N) {
        C[row * N + col] = acc;
    }
}


// ============================================================================
// Kernel 3: CSR Random Walk Step (conceptual)
// ============================================================================
//
// When the transfer matrix P is sparse, CSR format reduces memory and
// enables coalesced access.  This kernel demonstrates one step of a
// random walk over a CSR-encoded transition matrix.

__global__ void csr_walk_step_kernel(
    const float* __restrict__ P_values,   // CSR non-zero values
    const int* __restrict__ P_col_idx,    // CSR column indices
    const int* __restrict__ P_row_ptr,    // CSR row pointers
    const int* __restrict__ current_nodes,// (total_walkers,)
    int* __restrict__ next_nodes,         // (total_walkers,) output
    unsigned int* __restrict__ rand_state,// cuRAND states (per thread)
    int total_walkers,
    int N
) {
    int wid = blockIdx.x * blockDim.x + threadIdx.x;
    if (wid >= total_walkers) return;

    int cur = current_nodes[wid];

    // CSR range for this row
    int start = P_row_ptr[cur];
    int end   = P_row_ptr[cur + 1];

    if (start == end) {
        // Degenerate row: stay in place (or uniform fallback).
        next_nodes[wid] = cur;
        return;
    }

    // Generate uniform random number via cuRAND device API.
    // In production: curand_uniform(&rand_state[wid]) returns (0,1].
    float p = curand_uniform(&rand_state[wid]);

    // Linear scan of the CSR row (acceptable for low-degree graphs).
    // For high-degree nodes, binary search on prefix-sum would be used.
    float cumsum = 0.0f;
    int next = P_col_idx[start];
    for (int j = start; j < end; j++) {
        cumsum += P_values[j];
        if (p <= cumsum) {
            next = P_col_idx[j];
            break;
        }
    }

    next_nodes[wid] = next;
}


